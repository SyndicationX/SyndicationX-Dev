import { SESSION_USER_DETAILS_KEY } from "./sessionKeys"
import {
  formatMemberUsername,
  isAutoGeneratedPortalUsername,
} from "@/modules/Syndication/usermanagement/memberAdminShared"

function readSessionUserRow(): Record<string, unknown> | null {
  try {
    const raw = sessionStorage.getItem(SESSION_USER_DETAILS_KEY)
    if (!raw) return null
    const parsed = JSON.parse(raw) as unknown
    if (!Array.isArray(parsed) || parsed.length === 0) return null
    const entry = parsed[0]
    if (entry == null || typeof entry !== "object" || Array.isArray(entry))
      return null
    return entry as Record<string, unknown>
  } catch {
    return null
  }
}

function namePartsFromSessionUser(row: Record<string, unknown>): {
  firstName: string
  lastName: string
} {
  const firstName = String(row.firstName ?? row.first_name ?? "").trim()
  const lastName = String(row.lastName ?? row.last_name ?? "").trim()
  if (firstName || lastName) return { firstName, lastName }
  const username = String(row.username ?? "").trim()
  if (!username || isAutoGeneratedPortalUsername(username)) {
    return { firstName: "", lastName: "" }
  }
  const parts = formatMemberUsername(username).split(/\s+/).filter(Boolean)
  if (parts.length === 0 || parts[0] === "—") {
    return { firstName: "", lastName: "" }
  }
  if (parts.length === 1) return { firstName: parts[0]!, lastName: "" }
  return { firstName: parts[0]!, lastName: parts.slice(1).join(" ") }
}

function displayNameFromSessionUser(row: Record<string, unknown>): string {
  const first = String(row.firstName ?? row.first_name ?? "").trim()
  const last = String(row.lastName ?? row.last_name ?? "").trim()
  const full = [first, last].filter(Boolean).join(" ")
  if (full) return full
  const email = String(row.email ?? "").trim()
  if (email) return email
  const username = String(row.username ?? "").trim()
  if (username && !isAutoGeneratedPortalUsername(username)) {
    return formatMemberUsername(username)
  }
  return ""
}

/** First and last name for the signed-in user (`userDetails` in sessionStorage). */
export function getSessionUserNameParts(): {
  firstName: string
  lastName: string
} {
  const row = readSessionUserRow()
  if (!row) return { firstName: "", lastName: "" }
  return namePartsFromSessionUser(row)
}

/** Display name for the signed-in user (from `userDetails` in sessionStorage). */
export function getSessionUserDisplayName(): string {
  const row = readSessionUserRow()
  if (!row) return ""
  return displayNameFromSessionUser(row)
}
